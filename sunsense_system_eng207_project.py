# The fourth function
# This function analysis voltage data and caluclates min,max, average& std_dev
def calculate_statistics (voltage_data):

  # Check if data exists
  if len(voltage_data) == 0:
    print("No data available! Please create data first")
    return
    #min and max values
  min_Voltage = voltage_data[0]
  max_Voltage = voltage_data[0]
  total_Voltage = 0
  # average value
  for v in voltage_data:
    if v < min_Voltage:
      min_Voltage = v
    if v > max_Voltage:
      max_Voltage = v
    total_Voltage += v
  average_Voltage = total_Voltage / len(voltage_data)
   # calculate variance
  variance_Voltage = 0
  for v in voltage_data:
    variance_Voltage += (v - average_Voltage) ** 2
  variance_Voltage /= len(voltage_data)
   # standard deviation
  std_dev = math.sqrt(variance_Voltage)
  # print results
  print("Statistics: ")
  print(f"Minimum Voltage: {min_Voltage}V")
  print(f"Maximum Voltage: {max_Voltage}V")
  print(f"Average_Voltage: {average_Voltage:.2f}")
  print(f"Standard Deviation: {std_dev:.2f}")



