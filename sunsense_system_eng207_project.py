# Tuple ranges for voltage thresholds

NORMAL_RANGE = (15, 22)
WARNING_RANGE = (10, 15)

# function to check voltage levels and classify them as Normal , Waringing or Critcal
def threshold_monitoring(voltage_data):

  #check if there is no data
  if not voltage_data:
    print("No data available! Please create data first")
  else:
    warning_count = 0
    critical_count = 0

  # loop through all voltage readings
    for i in range(len(voltage_data)):
      voltage = voltage_data[i]

      # Check voltage level and assign status
      if NORMAL_RANGE[0] <= voltage <= NORMAL_RANGE[1]:
        status = "Normal"
      elif WARNING_RANGE[0] <= voltage <= NORMAL_RANGE[1]: # Corrected upper bound from WARNING_RANGE[1] to NORMAL_RANGE[1]
        status = "Warning"
        warning_count += 1

      else:
        status = "Critical"
        critical_count += 1

        # Print each reading with it status :
        print("Reading " ,i + 1 , ": Voltage = ", voltage, "V :",status)

    # Print total counts of warings ana critical counts
    print("Number of Warning Readings:", warning_count)
    print("Number of Critical Readings:", critical_count)

